"use client";

import React from "react";
import { MomentCandidate } from "@/lib/mockData";

interface AllCandidatesTabProps {
  candidates: MomentCandidate[];
  activeCandidate: MomentCandidate;
  onSelectCandidate: (candidate: MomentCandidate, autoPlay?: boolean) => void;
}

export function AllCandidatesTab({
  candidates,
  activeCandidate,
  onSelectCandidate,
}: AllCandidatesTabProps) {
  return (
    <div className="w-full bg-white rounded-3xl p-5 sm:p-6 border border-[#E5E7EB] shadow-xs flex flex-col gap-4">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 pb-2 border-b border-[#E5E7EB]">
        <div>
          <h3 className="text-base font-bold text-[#111111]">
            All Candidate Proposals ({candidates.length})
          </h3>
          <p className="text-xs text-[#6B7280]">
            Candidate temporal windows generated by Moment-DETR proposal queries.
          </p>
        </div>
        <span className="text-xs font-mono text-[#6B7280] bg-[#F8F9FA] px-2.5 py-1 rounded-full border border-[#E5E7EB]">
          Demo simulation • Hungarian match ranking
        </span>
      </div>

      {/* Responsive Proposals Table */}
      <div className="overflow-x-auto">
        <table className="w-full text-left text-xs sm:text-sm">
          <thead>
            <tr className="border-b border-[#E5E7EB] text-[#6B7280] font-semibold">
              <th className="py-2.5 px-3">Rank</th>
              <th className="py-2.5 px-3">Interval</th>
              <th className="py-2.5 px-3">Duration</th>
              <th className="py-2.5 px-3">Raw Score</th>
              <th className="py-2.5 px-3">Context / Event</th>
              <th className="py-2.5 px-3 text-right">Action</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-[#E5E7EB]/60">
            {candidates.map((cand) => {
              const isSelected = activeCandidate.id === cand.id;
              const isTop = cand.isTopMatch;

              return (
                <tr
                  key={cand.id}
                  onClick={() => onSelectCandidate(cand, true)}
                  className={`cursor-pointer transition-colors ${
                    isSelected
                      ? "bg-[#FFF0F5] font-semibold"
                      : "hover:bg-[#F8F9FA]"
                  }`}
                >
                  <td className="py-3 px-3 font-mono font-bold text-[#111111]">
                    {cand.label}
                  </td>
                  <td className="py-3 px-3 font-mono font-bold">
                    <span
                      className={
                        isTop
                          ? "text-[#FE2C55]"
                          : isSelected
                          ? "text-[#111111]"
                          : "text-[#111111]"
                      }
                    >
                      {cand.startFormatted} – {cand.endFormatted}
                    </span>
                  </td>
                  <td className="py-3 px-3 font-mono text-[#6B7280]">
                    {cand.durationSeconds.toFixed(1)}s
                  </td>
                  <td className="py-3 px-3 font-mono">
                    <span className="px-2 py-0.5 rounded-md bg-[#F3F4F6] text-[#4B5563] text-xs font-bold">
                      {cand.rawScore?.toFixed(3) ?? "0.000"}
                    </span>
                  </td>
                  <td className="py-3 px-3 text-[#6B7280] max-w-xs truncate">
                    {cand.description}
                  </td>
                  <td className="py-3 px-3 text-right">
                    <button
                      type="button"
                      onClick={(e) => {
                        e.stopPropagation();
                        onSelectCandidate(cand, true);
                      }}
                      className={`px-3 py-1 rounded-full text-xs font-bold cursor-pointer transition-all ${
                        isSelected
                          ? "bg-[#FE2C55] text-white shadow-xs"
                          : "bg-white text-[#111111] border border-[#E5E7EB] hover:border-[#111111]"
                      }`}
                    >
                      Play
                    </button>
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
    </div>
  );
}

